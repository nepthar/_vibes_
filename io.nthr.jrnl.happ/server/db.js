import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const dataDir = process.env.JRNL_DATA ?? join(root, 'data');
export const mediaDir = join(dataDir, 'media');

mkdirSync(mediaDir, { recursive: true });

export const db = new DatabaseSync(join(dataDir, 'jrnl.db'));

// page_size and auto_vacuum only take on a new file (or after VACUUM), so they
// run before WAL creates pages. The rest apply to this connection every open.
for (const pragma of [
  'PRAGMA page_size = 4096',
  'PRAGMA auto_vacuum = INCREMENTAL',
  'PRAGMA journal_mode = WAL',
  'PRAGMA synchronous = NORMAL',
  'PRAGMA busy_timeout = 5000',
  'PRAGMA foreign_keys = ON',
  'PRAGMA cache_size = -64000',
  'PRAGMA mmap_size = 268435456',
  'PRAGMA temp_store = MEMORY',
]) {
  db.exec(pragma);
}

// UUID ids throughout; all timestamps are epoch milliseconds
// (UTC), with the entry's IANA zone stored alongside so export can render the
// wall-clock time the user experienced.
db.exec(`
CREATE TABLE IF NOT EXISTS users (
  id            TEXT PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE COLLATE NOCASE,
  password_hash TEXT NOT NULL,
  created_at    INTEGER NOT NULL,
  -- Per-user app state; the iOS app keeps these in UserDefaults.
  active_journal_id       TEXT,
  remembered_granularity  TEXT NOT NULL DEFAULT 'city'
);

CREATE TABLE IF NOT EXISTS sessions (
  token      TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

-- One-time invites. The operator mints these with npm run signup-token;
-- they last a week and are deleted the moment they create an account.
CREATE TABLE IF NOT EXISTS signup_tokens (
  token      TEXT PRIMARY KEY,
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS journals (
  id         TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  created_at INTEGER NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS journals_user_name
  ON journals(user_id, name COLLATE NOCASE);

-- Committed journal entries, and nothing else. Every row here is in the
-- journal: immutable, and only ever added to. That is what makes syncing two
-- devices a set union rather than a negotiation.
CREATE TABLE IF NOT EXISTS entries (
  id                  TEXT PRIMARY KEY,   -- generated by the client
  user_id             TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  journal_id          TEXT NOT NULL REFERENCES journals(id) ON DELETE CASCADE,
  -- The client's clock. For a journal the user's wall clock is the right
  -- authority: if their machine says Tuesday, the entry says Tuesday.
  created_at          INTEGER NOT NULL,
  time_zone_id        TEXT NOT NULL,
  last_interaction_at INTEGER NOT NULL,
  -- The server's clock, never used for display. Kept so that a wrong client
  -- clock can be diagnosed rather than silently believed.
  received_at         INTEGER NOT NULL DEFAULT 0,
  -- EntryLocation, flattened: exactly granularity + display name + one
  -- coordinate at that granularity. NULL granularity ⇒ untagged.
  loc_granularity  TEXT,
  loc_display_name TEXT,
  loc_latitude     REAL,
  loc_longitude    REAL,
  loc_resolved     INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS entries_journal ON entries(journal_id, created_at DESC);

-- Scratch space for writing in progress — one slot per device, so two devices
-- never contend for it. Purely a crash-recovery buffer: a commit carries the
-- entry's full content, so nothing here is ever needed to produce a journal
-- entry, and losing a slot costs at most the last few seconds of typing.
CREATE TABLE IF NOT EXISTS drafts (
  user_id      TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  device_id    TEXT NOT NULL,
  entry_id     TEXT NOT NULL,     -- the id this will commit as, chosen by the client
  journal_id   TEXT NOT NULL,
  content      TEXT NOT NULL,     -- JSON block list
  location     TEXT,              -- JSON EntryLocation, or NULL
  started_at   INTEGER NOT NULL,  -- client clock: becomes the entry's created_at
  time_zone_id TEXT NOT NULL,
  -- Client clock at the last update. Monotonic guard: an update carrying an
  -- older stamp than the one stored is a stale writer and is refused.
  client_time  INTEGER NOT NULL,
  received_at  INTEGER NOT NULL,
  -- Absolute server time at which the janitor may commit this slot. Derived
  -- from the client's finalize_in (seconds from now) on every draft update.
  finalize_at  INTEGER,
  PRIMARY KEY (user_id, device_id)
);
CREATE INDEX IF NOT EXISTS drafts_finalize ON drafts(finalize_at);

CREATE TABLE IF NOT EXISTS blocks (
  id           TEXT PRIMARY KEY,
  entry_id     TEXT NOT NULL REFERENCES entries(id) ON DELETE CASCADE,
  idx          INTEGER NOT NULL,
  kind         TEXT NOT NULL,
  text         TEXT,
  asset_id     TEXT,
  url          TEXT,          -- third-party media; asset_id is a local upload
  media_type   TEXT,
  pixel_width  INTEGER,
  pixel_height INTEGER,
  duration     REAL
);
CREATE INDEX IF NOT EXISTS blocks_entry ON blocks(entry_id, idx);

-- The web analog of a PhotoKit pointer: the iOS app stores an asset id and
-- resolves the bytes from the device library, so here the bytes live on the
-- server and blocks store this row's id.
CREATE TABLE IF NOT EXISTS media (
  id           TEXT PRIMARY KEY,
  user_id      TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  media_type   TEXT NOT NULL,
  mime         TEXT NOT NULL,
  byte_size    INTEGER NOT NULL,
  pixel_width  INTEGER,
  pixel_height INTEGER,
  duration     REAL,
  created_at   INTEGER NOT NULL
);

-- Geocoding results, cached so repeated writing from one place doesn't hammer
-- the upstream services (and so the app still resolves names while offline).
CREATE TABLE IF NOT EXISTS geo_cache (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  created_at INTEGER NOT NULL
);

-- Global publish-job watermarks. One row; change_at advances whenever any
-- entry's published flag flips, and last_success_at advances after a clean run.
CREATE TABLE IF NOT EXISTS publish_meta (
  id               INTEGER PRIMARY KEY CHECK (id = 1),
  change_at        INTEGER NOT NULL DEFAULT 0,
  last_success_at  INTEGER NOT NULL DEFAULT 0
);
INSERT OR IGNORE INTO publish_meta (id, change_at, last_success_at) VALUES (1, 0, 0);
`);

// Additive migrations for existing databases (CREATE TABLE IF NOT EXISTS
// above does not alter columns on an already-created entries table).
for (const column of [
  'ALTER TABLE entries ADD COLUMN published INTEGER NOT NULL DEFAULT 0',
  'ALTER TABLE entries ADD COLUMN publish_slug TEXT',
]) {
  try {
    db.exec(column);
  } catch {
    // Column already present.
  }
}

db.exec(`
CREATE UNIQUE INDEX IF NOT EXISTS entries_user_publish_slug
  ON entries(user_id, publish_slug) WHERE publish_slug IS NOT NULL;
`);

export const publishedDir = join(dataDir, 'published');
mkdirSync(publishedDir, { recursive: true });

export const uuid = () => crypto.randomUUID();
export const now = () => Date.now();
